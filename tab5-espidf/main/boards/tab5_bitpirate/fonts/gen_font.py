#!/usr/bin/env python3
"""Regenerates lv_font_pirate_mono.c from DejaVu Sans Mono.

Rasterizes ASCII 0x20-0x7F at a fixed cell size using Pillow, packs each
glyph as a flat MSB-first 1bpp bitmap (no row padding -- matches LVGL's
LV_FONT_FMT_TXT_PLAIN format, confirmed against lv_font_unscii_16.c's own
byte offsets), and emits an lv_font_t compatible with LVGL 8.3's
lv_font_fmt_txt_dsc_t. Every glyph uses the full cell as its box (uniform
ofs_x=ofs_y=0), with the character's baseline pre-positioned at y=ascent
within that cell -- so no per-glyph offset math is needed at draw time.

Needs: pip install Pillow (or apt install python3-pil), and the
fonts-dejavu-core package (DejaVuSansMono.ttf) for the source font.

Run from anywhere; writes lv_font_pirate_mono.c next to this script.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE = 22  # gives ascent+descent=27, matching Montserrat 24's own line_height
          # (used elsewhere in the GUI) -- see Tab5Gui.cpp's termFont() comment.
RANGE_START = 0x20
RANGE_END = 0x7F  # inclusive, matches unscii_16's 0x20-0x7F (96 chars)
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "lv_font_pirate_mono.c")


def main():
    font = ImageFont.truetype(FONT_PATH, SIZE)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    adv_w_px = font.getlength("M")
    if not all(font.getlength(chr(c)) == adv_w_px for c in range(RANGE_START, RANGE_END + 1)):
        sys.exit("source font is not uniform-width in this range -- pick a real monospace font")
    cell_w = round(adv_w_px)
    adv_w_fixed = round(adv_w_px * 16)  # LVGL adv_w units: real_px*16, recovered via (adv_w+8)>>4

    glyph_entries = [(0, 0, 0, 0, 0, 0)]  # id 0 reserved
    bitmap_blob = bytearray()

    for cp in range(RANGE_START, RANGE_END + 1):
        img = Image.new("L", (cell_w, cell_h), color=0)
        draw = ImageDraw.Draw(img)
        draw.text((0, ascent), chr(cp), font=font, fill=255, anchor="ls")
        px = img.load()

        bits = [1 if px[x, y] >= 128 else 0 for y in range(cell_h) for x in range(cell_w)]
        packed = bytearray((len(bits) + 7) // 8)
        for i, b in enumerate(bits):
            if b:
                packed[i // 8] |= 0x80 >> (i % 8)

        glyph_entries.append((len(bitmap_blob), cell_w, cell_h, 0, 0, adv_w_fixed))
        bitmap_blob.extend(packed)

    out = []
    out.append("/* Generated by gen_font.py from DejaVu Sans Mono -- real monospace glyph")
    out.append(" * proportions. unscii_16's retro pixel-art glyph shapes don't form the")
    out.append(" * FIGlet block-letter banner correctly even though positioning is correct;")
    out.append(" * see Tab5Gui.cpp's termFont() comment for the full story. Re-run this")
    out.append(" * script (needs Pillow + fonts-dejavu-core) to regenerate. */")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("static const uint8_t glyph_bitmap[] = {")
    out.append("  " + ",\n  ".join(
        ", ".join(f"0x{bitmap_blob[j]:02x}" for j in range(i, min(i + 16, len(bitmap_blob))))
        for i in range(0, len(bitmap_blob), 16)
    ))
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    for bi, bw, bh, ox, oy, aw in glyph_entries:
        out.append(f"    {{.bitmap_index = {bi}, .adv_w = {aw}, .box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append("    {")
    out.append(f"        .range_start = {RANGE_START}, .range_length = {RANGE_END - RANGE_START + 1}, .glyph_id_start = 1,")
    out.append("        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY")
    out.append("    }")
    out.append("};")
    out.append("")
    out.append("static lv_font_fmt_txt_glyph_cache_t cache;")
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 1,")
    out.append("    .bpp = 1,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("    .cache = &cache")
    out.append("};")
    out.append("")
    out.append("const lv_font_t lv_font_pirate_mono = {")
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append(f"    .line_height = {cell_h},")
    out.append("    .base_line = 0,")
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append("    .underline_position = 0,")
    out.append("    .underline_thickness = 0,")
    out.append("    .dsc = &font_dsc")
    out.append("};")

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT_PATH}: {len(glyph_entries)} glyphs, {len(bitmap_blob)} bitmap bytes, "
          f"cell {cell_w}x{cell_h}", file=sys.stderr)


if __name__ == "__main__":
    main()
